"""Fixture-backed data providers (``DATA_PROVIDER_MODE=mock``, the default).

The fixtures under ``fixtures/`` are generated by ``generate_fixtures.py`` and committed, so
tests see the same deeds, signals and contacts on every run. Each provider also records its
calls so tests and the synthetic pilot can assert on provider traffic.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path
from typing import Any

from wholesaling.db.normalize import normalize_entity_name
from wholesaling.integrations.base import HealthStatus, IntegrationMode
from wholesaling.integrations.data.interface import DataProviders
from wholesaling.integrations.data.models import (
    ContactCandidate,
    DeedRecord,
    MarketRef,
    MarketSignals,
    ReferenceLists,
)

FIXTURES_DIR = Path(__file__).resolve().parent / "fixtures"


def _load(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as fh:
        return json.load(fh)


@dataclass(slots=True)
class MockDeedRecordsProvider:
    name: str = "deed_records"
    mode: IntegrationMode = "mock"
    records: list[DeedRecord] = field(default_factory=list)
    calls: list[dict[str, Any]] = field(default_factory=list)
    healthy: bool = True

    @classmethod
    def from_fixtures(cls, fixtures_dir: Path = FIXTURES_DIR) -> MockDeedRecordsProvider:
        raw = _load(fixtures_dir / "deeds.json")
        return cls(records=[DeedRecord.from_json(d) for d in raw])

    async def purchases(self, market: MarketRef, since: date, until: date) -> list[DeedRecord]:
        self.calls.append(
            {"method": "purchases", "market": market.label, "since": since, "until": until}
        )
        return [
            r
            for r in self.records
            if r.city == market.name and r.state == market.state and since <= r.sale_date <= until
        ]

    async def healthcheck(self) -> HealthStatus:
        return HealthStatus(
            name=self.name,
            mode=self.mode,
            ok=self.healthy,
            detail=f"{len(self.records)} fixture deeds",
        )


@dataclass(slots=True)
class MockMarketSignalsProvider:
    name: str = "market_signals"
    mode: IntegrationMode = "mock"
    by_market: dict[MarketRef, MarketSignals] = field(default_factory=dict)
    calls: list[dict[str, Any]] = field(default_factory=list)
    healthy: bool = True

    @classmethod
    def from_fixtures(cls, fixtures_dir: Path = FIXTURES_DIR) -> MockMarketSignalsProvider:
        raw = _load(fixtures_dir / "signals.json")
        signals = [MarketSignals.from_json(d) for d in raw]
        return cls(by_market={s.market: s for s in signals})

    async def signals(self, market: MarketRef) -> MarketSignals:
        self.calls.append({"method": "signals", "market": market.label})
        found = self.by_market.get(market)
        if found is None:
            return MarketSignals(market=market, data_available=False, source=self.name)
        return found

    async def healthcheck(self) -> HealthStatus:
        return HealthStatus(
            name=self.name, mode=self.mode, ok=self.healthy, detail=f"{len(self.by_market)} markets"
        )


@dataclass(slots=True)
class MockContactEnrichmentProvider:
    name: str = "contact_enrichment"
    mode: IntegrationMode = "mock"
    by_entity_key: dict[str, list[ContactCandidate]] = field(default_factory=dict)
    calls: list[dict[str, Any]] = field(default_factory=list)
    healthy: bool = True

    @classmethod
    def from_fixtures(cls, fixtures_dir: Path = FIXTURES_DIR) -> MockContactEnrichmentProvider:
        raw = _load(fixtures_dir / "contacts.json")
        return cls(
            by_entity_key={k: [ContactCandidate.from_json(c) for c in v] for k, v in raw.items()}
        )

    async def lookup(
        self,
        entity_name: str,
        mailing_address: str | None,
        registered_agent: str | None = None,
    ) -> list[ContactCandidate]:
        self.calls.append(
            {
                "method": "lookup",
                "entity_name": entity_name,
                "mailing_address": mailing_address,
                "registered_agent": registered_agent,
            }
        )
        return list(self.by_entity_key.get(normalize_entity_name(entity_name), []))

    async def healthcheck(self) -> HealthStatus:
        return HealthStatus(
            name=self.name,
            mode=self.mode,
            ok=self.healthy,
            detail=f"{len(self.by_entity_key)} entities with contacts",
        )


def load_reference_lists(fixtures_dir: Path = FIXTURES_DIR) -> ReferenceLists:
    raw = _load(fixtures_dir / "reference_lists.json")
    return ReferenceLists(
        institutional=frozenset(raw.get("institutional", [])),
        licensed_agents=frozenset(raw.get("licensed_agents", [])),
        suppressed=frozenset(raw.get("suppressed", [])),
    )


def mock_data_providers(fixtures_dir: Path = FIXTURES_DIR) -> DataProviders:
    return DataProviders(
        deeds=MockDeedRecordsProvider.from_fixtures(fixtures_dir),
        signals=MockMarketSignalsProvider.from_fixtures(fixtures_dir),
        contacts=MockContactEnrichmentProvider.from_fixtures(fixtures_dir),
        reference_lists=load_reference_lists(fixtures_dir),
    )


__all__ = [
    "FIXTURES_DIR",
    "MockContactEnrichmentProvider",
    "MockDeedRecordsProvider",
    "MockMarketSignalsProvider",
    "load_reference_lists",
    "mock_data_providers",
]
